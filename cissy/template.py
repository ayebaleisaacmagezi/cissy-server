def ios_usage_descriptions(config: AppConfig) -> dict[str, str]:
    """Info.plist reasons for every permission the app can request.

    A missing one is not a warning — iOS terminates the app the moment the
    permission is requested, and App Store review rejects the build.
    """
    features = set(config.features)
    values: dict[str, str] = {}
    if "Camera" in features:
        values["NSCameraUsageDescription"] = config.permission_description("camera")
    if "Camera" in features or "File upload" in features:
        values["NSPhotoLibraryUsageDescription"] = config.permission_description(
            "photos"
        )
    if "Location" in features:
        values["NSLocationWhenInUseUsageDescription"] = config.permission_description(
            "location"
        )
    return values


def _host_of(url: str) -> str:
    from urllib.parse import urlparse

    return (urlparse(url).hostname or "").lower()
