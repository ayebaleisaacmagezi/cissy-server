def pubspec(
    config: AppConfig,
    splash_asset: str | None = None,
    icon_asset: str | None = None,
) -> str:
    features = set(config.features)
    lines = [
        f"name: {project_name(config)}",
        "description: Generated by Cissy.",
        "publish_to: none",
        f"version: {config.version_name}+{config.version_code}",
        "",
        "environment:",
        "  sdk: ^3.9.0",
        "",
        "dependencies:",
        "  flutter:",
        "    sdk: flutter",
        f"  flutter_inappwebview: {DEPENDENCIES['flutter_inappwebview']}",
        f"  url_launcher: {DEPENDENCIES['url_launcher']}",
    ]
    if "Native sharing" in features:
        lines.append(f"  share_plus: {DEPENDENCIES['share_plus']}")
    if "Location" in features:
        lines.append(f"  geolocator: {DEPENDENCIES['geolocator']}")
    if "Downloads" in features:
        lines.append(f"  path_provider: {DEPENDENCIES['path_provider']}")
        lines.append(f"  open_filex: {DEPENDENCIES['open_filex']}")
    if "Deep links" in features:
        lines.append(f"  app_links: {DEPENDENCIES['app_links']}")

    lines += [
        "",
        "dev_dependencies:",
        "  flutter_test:",
        "    sdk: flutter",
        "  flutter_lints: ^5.0.0",
    ]
    if icon_asset:
        lines.append(f"  flutter_launcher_icons: {DEPENDENCIES['flutter_launcher_icons']}")

    lines += [
        "",
        "flutter:",
        "  uses-material-design: true",
    ]
    if splash_asset:
        lines += ["  assets:", f"    - {splash_asset}"]

    if icon_asset:
        # Android reads the launcher icon from five mipmap densities and iOS
        # from about fifteen sizes in an appiconset. Generating those needs an
        # image library, which this server does not have — so the sizes are
        # produced by flutter_launcher_icons on the build machine instead,
        # where the Dart toolchain already is.
        lines += [
            "",
            "flutter_launcher_icons:",
            "  android: true",
            "  ios: true",
            f"  image_path: {icon_asset}",
            "  min_sdk_android: 21",
            # iOS rejects an icon with an alpha channel, and a logo exported
            # with a transparent background is the normal case.
            "  remove_alpha_ios: true",
        ]
    return "\n".join(lines) + "\n"


# ── main.dart ────────────────────────────────────────────────────────────


def main_dart(config: AppConfig, splash_asset: str | None = None) -> str:
    features = set(config.features)
    has_share = "Native sharing" in features
    has_location = "Location" in features
    has_downloads = "Downloads" in features
    has_deep_links = "Deep links" in features
    has_pull_refresh = "Pull to refresh" in features
    has_camera = "Camera" in features
    has_uploads = "File upload" in features
    has_fallback = config.offline_fallback_enabled
    has_bridge = has_share or has_location

    out: list[str] = []
    add = out.append

    # ── imports ──
    add("import 'dart:async';")
    if has_downloads:
        add("import 'dart:io';")
    add("")
    add("import 'package:flutter/material.dart';")
    add("import 'package:flutter/services.dart';")
    add("import 'package:flutter_inappwebview/flutter_inappwebview.dart';")
    add("import 'package:url_launcher/url_launcher.dart';")
    if has_share:
        add("import 'package:share_plus/share_plus.dart';")
    if has_location:
        add("import 'package:geolocator/geolocator.dart';")
    if has_downloads:
        add("import 'package:open_filex/open_filex.dart';")
        add("import 'package:path_provider/path_provider.dart';")
    if has_deep_links:
        add("import 'package:app_links/app_links.dart';")
    add("")

    # ── constants ──
    domains = [d.lower() for d in config.allowed_domains]
    add(f"const homeUrl = {dart_string(config.website_url)};")
    add(f"const allowedDomains = <String>{json.dumps(domains)};")
    add(f"const requireHttps = {_dart_bool(config.require_https)};")
    add(f"const externalLinkBehavior = {dart_string(config.external_link_behavior)};")
    if has_deep_links:
        add(f"const deepLinkScheme = {dart_string(deep_link_scheme(config))};")
    add("")

    if has_fallback:
        add(_OFFLINE_ERROR_TYPES)

    # ── entry point ──
    add(_MAIN_FUNCTION)
    add(_APP_WIDGET.replace("__TITLE__", dart_string(config.display_name)))
    add(_SCREEN_HEADER)

    if has_fallback:
        add(
            "  String? errorTitle;\n"
            "  String? errorMessage;\n"
            "  String? currentUrl;\n"
            "  bool errorIsOffline = false;"
        )
    add("")

    # ── initState ──
    add("  @override")
    add("  void initState() {")
    add("    super.initState();")
    if has_pull_refresh:
        add("    pullToRefreshController = PullToRefreshController(")
        add("      onRefresh: () async => controller?.reload(),")
        add("    );")
    if has_deep_links:
        add("    _listenForDeepLinks();")
    add("  }")
    add("")

    if has_deep_links:
        add(_DEEP_LINKS)

    add(_LOAD_TIMEOUT)
    add(_FINISH_LOAD)
    add(_finish_failed_load(has_fallback))

    if has_fallback:
        add(_FAILURE_CLASSIFIERS)

    add(_ALLOWED_HOST)

    if has_deep_links:
        add(_ALLOWED_WEB_URI)

    add(_DECIDE_NAVIGATION)

    # `_load` is only reachable from deep links or the retry buttons. Emitting
    # it otherwise leaves dead code, which fails the generated project's own
    # flutter_lints run.
    if has_deep_links or has_fallback:
        add(_load_method(has_fallback))

    add(_HANDLE_BACK)
    add(_page_policies(has_uploads))

    if has_bridge:
        add(_bridge(has_share, has_location))

    if has_downloads:
        add(_DOWNLOAD)

    add(_SHOW_MESSAGE)
    add(
        _build_method(
            config,
            splash_asset=splash_asset,
            has_fallback=has_fallback,
            has_bridge=has_bridge,
            has_downloads=has_downloads,
            has_camera=has_camera,
        )
    )
    add(_DISPOSE)

    if has_fallback:
        add(_ERROR_VIEW)

    return "\n".join(out).rstrip() + "\n"


def _dart_bool(value: bool) -> str:
    return "true" if value else "false"


